"""Pydantic data schemas for video generation pipeline."""
from typing import List
from pydantic import BaseModel, Field


class Scene(BaseModel):
    """Represents a single scene in the video script."""
    scene_id: int = Field(
        ...,
        description="Sequential index of the scene, starting at 1"
    )
    narration: str = Field(
        ...,
        description="Spoken text for this scene (punchy, engaging, suitable for TTS voiceover)"
    )
    visual_description: str = Field(
        ...,
        description="Clear visual description of what should appear on screen"
    )
    search_keywords: List[str] = Field(
        ...,
        description="List of 2-4 literal, descriptive search keywords optimized for stock video libraries (e.g. ['drone sunset ocean', 'nature waves aerial'])"
    )


class VideoScript(BaseModel):
    """Complete video script payload generated by the LLM."""
    title: str = Field(
        ...,
        description="Catchy, viral title for the short-form video"
    )
    description: str = Field(
        ...,
        description="SEO-friendly caption/description for YouTube Shorts / TikTok"
    )
    tags: List[str] = Field(
        default_factory=list,
        description="List of relevant hashtags and keywords (without the # symbol)"
    )
    scenes: List[Scene] = Field(
        ...,
        description="Ordered list of scenes comprising the video"
    )
